#!/usr/bin/env node
// Regenerates src/themes/registry.generated.ts from the files in src/themes/{paradigms,setpieces,dna}.
// Run after adding/removing a theme file:  node scripts/gen-theme-registry.mjs
import { readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "themes");
const ls = (d, ext) => (existsSync(join(root, d)) ? readdirSync(join(root, d)).filter((f) => f.endsWith(ext)).sort() : []);
const id = (f) => f.replace(/\.[^.]+$/, "");
const v = (p, f) => `${p}_${id(f).replace(/[^a-zA-Z0-9]/g, "_")}`;

const par = ls("paradigms", ".tsx");
const set = ls("setpieces", ".tsx");
const dna = ls("dna", ".json");

let out = "// GENERATED by scripts/gen-theme-registry.mjs. Do not edit by hand.\n";
out += 'import type { Paradigm, Setpiece, ThemeDNA } from "./types";\n';
if (dna.length) out += 'import { themeDNA } from "./types";\n';
for (const f of par) out += `import ${v("p", f)} from "./paradigms/${id(f)}";\n`;
for (const f of set) out += `import ${v("s", f)} from "./setpieces/${id(f)}";\n`;
for (const f of dna) out += `import ${v("d", f)} from "./dna/${f}";\n`;
out += "\nexport const paradigms: Record<string, Paradigm> = {\n" + par.map((f) => `  "${id(f)}": ${v("p", f)},`).join("\n") + "\n};\n";
out += "\nexport const setpieces: Record<string, Setpiece> = {\n" + set.map((f) => `  "${id(f)}": ${v("s", f)},`).join("\n") + "\n};\n";
out += "\nexport const dnas: Record<string, ThemeDNA> = {\n" + dna.map((f) => `  "${id(f)}": themeDNA.parse(${v("d", f)}),`).join("\n") + "\n};\n";
writeFileSync(join(root, "registry.generated.ts"), out);
console.log(`registry: ${par.length} paradigms, ${set.length} setpieces, ${dna.length} themes`);
