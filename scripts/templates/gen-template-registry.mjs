#!/usr/bin/env node
// Regenerates src/templates/registry.generated.ts from the files in src/templates/*.tsx (except ae/types).
// Run after adding/removing a template:  node scripts/templates/gen-template-registry.mjs
import { readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "src", "templates");
const files = readdirSync(root).filter((f) => f.endsWith(".tsx") && !f.startsWith("ae") && !f.startsWith("registry")).sort();
const id = (f) => f.replace(/\.tsx$/, "");
const v = (f) => "t_" + id(f).replace(/[^a-zA-Z0-9]/g, "_");
let out = "// GENERATED by scripts/templates/gen-template-registry.mjs. Do not edit by hand.\n";
out += 'import type { TemplateDef } from "./types";\n';
for (const f of files) out += `import ${v(f)} from "./${id(f)}";\n`;
out += "\nexport const templates: Record<string, TemplateDef> = {\n" + files.map((f) => `  "${id(f)}": ${v(f)},`).join("\n") + "\n};\n";
writeFileSync(join(root, "registry.generated.ts"), out);
console.log(`template registry: ${files.length} templates`);
